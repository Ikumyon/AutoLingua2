// Physical pixel coordinates of the original, unmodified WebP captures.
function label(text: TextKey, x: number, y: number, width: number, height = 28,
  background = '#1f1f1f', fontSize = 18, button = false): ImageLabel {
  return { text, x, y, width, height, background, fontSize, button, fit: true,
    color: background === '#9deafa' || background === '#45bdf6' ? '#15222b' : undefined };
}
type ShotKey = Extract<TextKey, `details.shots.${string}`>;
type ShotName = ShotKey extends `details.shots.${infer Name}` ? Name : never;
const s = (key: ShotName) => `details.shots.${key}` as ShotKey;
const item = (key: ShotName, x: number, y: number, width: number, height = 28,
  background = '#1f1f1f', fontSize = 18) => label(s(key), x, y, width, height, background, fontSize);
const button = (key: ShotName, x: number, y: number, width: number, height = 30,
  background = '#2b2b2b', fontSize = 18) => label(s(key), x, y, width, height, background, fontSize, true);

